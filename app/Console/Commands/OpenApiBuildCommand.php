<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Filesystem\Filesystem;
use Symfony\Component\Yaml\Yaml;

/**
 * Phase 8 (2026-10-26) — aggregates every per-module OpenAPI fragment
 * `make:module --with-openapi` writes to `docs/openapi/modules/*.yaml`
 * into one root document, `docs/openapi/openapi.yaml`.
 *
 * Deliberately a separate, derived build step rather than something
 * `make:module` writes directly: a module's own fragment only needs to
 * know about itself, while the aggregate needs to see every module at
 * once (and is meant to be regenerated — idempotent by construction,
 * since it's always fully rebuilt from the fragments, never
 * incrementally patched).
 *
 * `--postman` additionally emits a Postman v2.1 collection
 * (`docs/postman/collection.json`) and a matching environment template
 * (`docs/postman/environment.json`, variables only — `bearer_token` is
 * left blank, never a real credential) from the SAME aggregated paths,
 * so the two artifacts can never drift from each other.
 */
class OpenApiBuildCommand extends Command
{
    protected $signature = 'openapi:build {--postman : Also emit a Postman v2.1 collection + environment template from the same aggregated paths}';

    protected $description = 'Aggregate every docs/openapi/modules/*.yaml fragment into docs/openapi/openapi.yaml (and, with --postman, a Postman collection)';

    public function handle(Filesystem $files): int
    {
        $fragmentDir = base_path('docs/openapi/modules');

        if (! $files->isDirectory($fragmentDir)) {
            $this->warn("No fragments directory found at {$fragmentDir} — nothing to aggregate. Generate at least one module with --with-openapi first.");

            return 0;
        }

        $fragmentPaths = $files->glob("{$fragmentDir}/*.yaml");
        if (empty($fragmentPaths)) {
            $this->warn('No .yaml fragments found — nothing to aggregate.');

            return 0;
        }

        $paths = [];
        $schemas = [];

        foreach ($fragmentPaths as $fragmentPath) {
            try {
                $fragment = Yaml::parseFile($fragmentPath);
            } catch (\Throwable $e) {
                $this->error('Failed to parse '.basename($fragmentPath).': '.$e->getMessage());

                return 1;
            }

            foreach ($fragment['paths'] ?? [] as $path => $operations) {
                if (isset($paths[$path])) {
                    // Two different modules documenting the exact same
                    // path is a real authoring conflict, not something to
                    // silently overwrite — surfaced, not swallowed.
                    $this->warn("Path \"{$path}\" is documented in more than one fragment — keeping the first, from an earlier file. Check ".basename($fragmentPath).' for a duplicate route prefix.');

                    continue;
                }
                $paths[$path] = $operations;
            }

            foreach ($fragment['components']['schemas'] ?? [] as $name => $schema) {
                $schemas[$name] = $schema;
            }
        }

        $document = [
            'openapi' => '3.0.3',
            'info' => [
                'title' => config('app.name', 'API').' — Generated API Reference',
                'version' => '1.0.0',
            ],
            'servers' => [['url' => '/']],
            'components' => [
                'securitySchemes' => [
                    'bearerAuth' => ['type' => 'http', 'scheme' => 'bearer'],
                ],
                'schemas' => $schemas,
            ],
            'paths' => $paths,
        ];

        $outputPath = base_path('docs/openapi/openapi.yaml');
        $yaml = Yaml::dump($document, 6, 2);
        $yaml = (string) preg_replace('/^(\s*)(\d{3}):$/m', "$1'$2':", $yaml);

        $files->put($outputPath, "# Generated by `php artisan openapi:build` (Phase 8, 2026-10-26).\n# Do not hand-edit — change the per-module fragment under docs/openapi/modules/\n# and re-run this command instead; any manual edit here is lost on rebuild.\n".$yaml);
        $this->info('Wrote '.count($paths).' paths and '.count($schemas)." schemas to {$outputPath}.");

        if ($this->option('postman')) {
            $this->buildPostmanArtifacts($files, $paths);
        }

        return 0;
    }

    /**
     * One Postman request item per path+method, read straight off the
     * SAME aggregated $paths this command just wrote to openapi.yaml —
     * so the collection can never describe a different set of endpoints
     * than the OpenAPI document does.
     */
    protected function buildPostmanArtifacts(Filesystem $files, array $paths): void
    {
        $items = [];

        foreach ($paths as $path => $operations) {
            foreach ($operations as $method => $operation) {
                $requiresAuth = ! empty($operation['security']);

                $item = [
                    'name' => $operation['summary'] ?? "{$method} {$path}",
                    'request' => [
                        'method' => strtoupper($method),
                        'header' => [
                            ['key' => 'Accept', 'value' => 'application/json'],
                        ],
                        'url' => [
                            'raw' => '{{base_url}}'.$path,
                            'host' => ['{{base_url}}'],
                            'path' => array_values(array_filter(explode('/', $path))),
                        ],
                    ],
                ];

                if ($requiresAuth) {
                    $item['request']['auth'] = [
                        'type' => 'bearer',
                        'bearer' => [['key' => 'token', 'value' => '{{bearer_token}}', 'type' => 'string']],
                    ];
                }

                $bodySchema = $operation['requestBody']['content']['application/json']['schema'] ?? null;
                if ($bodySchema) {
                    $example = [];
                    foreach ($bodySchema['properties'] ?? [] as $propName => $propSchema) {
                        $isBinary = ($propSchema['format'] ?? null) === 'binary';
                        $example[$propName] = match (true) {
                            $isBinary => null,
                            ($propSchema['type'] ?? 'string') === 'integer' => 1,
                            ($propSchema['type'] ?? 'string') === 'number' => 1.0,
                            ($propSchema['type'] ?? 'string') === 'boolean' => true,
                            ($propSchema['type'] ?? 'string') === 'array' => [],
                            default => "example-{$propName}",
                        };
                    }
                    $item['request']['header'][] = ['key' => 'Content-Type', 'value' => 'application/json'];
                    $item['request']['body'] = [
                        'mode' => 'raw',
                        'raw' => json_encode($example, JSON_PRETTY_PRINT),
                    ];
                }

                $items[] = $item;
            }
        }

        $collection = [
            'info' => [
                'name' => config('app.name', 'API').' — Generated Collection',
                'schema' => 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
            ],
            'item' => $items,
        ];

        $collectionPath = base_path('docs/postman/collection.json');
        $files->ensureDirectoryExists(dirname($collectionPath));
        $files->put($collectionPath, json_encode($collection, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));

        // Variables only — bearer_token is intentionally left blank.
        // Never a real credential; a developer pastes their own dev/test
        // token into Postman locally after importing this environment.
        $environment = [
            'name' => config('app.name', 'API').' — Generated Environment',
            'values' => [
                ['key' => 'base_url', 'value' => 'http://localhost:8000', 'enabled' => true],
                ['key' => 'bearer_token', 'value' => '', 'enabled' => true],
            ],
        ];
        $environmentPath = base_path('docs/postman/environment.json');
        $files->put($environmentPath, json_encode($environment, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));

        $this->info('Wrote '.count($items)." request(s) to {$collectionPath} and an environment template to {$environmentPath}.");
    }
}
