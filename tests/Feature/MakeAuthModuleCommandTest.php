<?php

namespace Tests\Feature;

use App\Http\Requests\Model\Auth\LoginRequest;
use App\Http\Requests\Model\Auth\RegisterRequest;
use App\Http\Requests\Model\Auth\RegisterVerifyRequest;
use App\Http\Requests\Model\Auth\ResetPassword\ResetPasswordRequest;
use App\Http\Requests\Model\Auth\ResetPassword\SendResetOtpRequest;
use App\Http\Requests\Model\Auth\ResetPassword\VerifyResetOtpRequest;
use App\Services\Auth\Otp\Channels\FakeOtpChannel;
use Illuminate\Http\Exceptions\HttpResponseException;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Route;
use Illuminate\Support\Facades\Schema;
use Tests\TestCase;

/**
 * Phase 2B (2026-10-25).
 *
 * This generator writes real project files (there is no sandboxed output
 * root for a model/service/controller generator) and edits
 * config/auth_modules.php and, optionally, DatabaseSeeder.php in place. To
 * keep the repository clean, every test uses the same disposable,
 * unmistakably-test-only module name ("DemoAccount") and tearDown()
 * removes every file it could have created plus reverts the two edited
 * files to their pre-test content, regardless of which test ran or
 * whether it passed. No migration generated by these tests is ever run
 * (`php artisan migrate` is never called here) — only file generation is
 * exercised.
 */
class MakeAuthModuleCommandTest extends TestCase
{
    protected string $name = 'DemoAccount';

    protected string $guard = 'demo_account';

    protected string $table = 'demo_accounts';

    protected string $routeFile = 'demo-account';

    protected string $authModulesConfigPath;

    protected string $authModulesConfigOriginal;

    protected string $databaseSeederPath;

    protected string $databaseSeederOriginal;

    protected function setUp(): void
    {
        parent::setUp();

        $this->authModulesConfigPath = config_path('auth_modules.php');
        $this->authModulesConfigOriginal = File::get($this->authModulesConfigPath);

        $this->databaseSeederPath = database_path('seeders/DatabaseSeeder.php');
        $this->databaseSeederOriginal = File::get($this->databaseSeederPath);
    }

    protected function tearDown(): void
    {
        File::put($this->authModulesConfigPath, $this->authModulesConfigOriginal);
        File::put($this->databaseSeederPath, $this->databaseSeederOriginal);

        // test_otp_flag_generates_a_real_register_verify_login_flow() runs
        // its migration explicitly (not via RefreshDatabase — see that
        // test's doc comment) against the shared sqlite `:memory:` test
        // connection, which can persist across test methods/classes within
        // one PHPUnit process. Drop the table and its migration-tracking
        // row so no later test in the suite sees it.
        if (Schema::hasTable($this->table)) {
            Schema::dropIfExists($this->table);
        }
        if (Schema::hasTable('migrations')) {
            DB::table('migrations')
                ->where('migration', 'like', "%_create_{$this->table}_table")
                ->delete();
        }

        foreach (File::glob(database_path("migrations/*_create_{$this->table}_table.php")) as $path) {
            File::delete($path);
        }

        foreach ([
            app_path("Models/{$this->name}.php"),
            database_path("factories/{$this->name}Factory.php"),
            app_path("Services/Functional/{$this->name}AuthService.php"),
            app_path("Http/Controllers/Auth/{$this->name}AuthController.php"),
            app_path("Http/Resources/Model/{$this->name}Resource.php"),
            app_path("Facades/Services/Auth/{$this->name}AuthFacade.php"),
            app_path("Policies/{$this->name}Policy.php"),
            base_path("routes/api/v1/{$this->routeFile}.php"),
            base_path("tests/Feature/{$this->name}AuthModuleTest.php"),
        ] as $path) {
            if (File::exists($path)) {
                File::delete($path);
            }
        }

        $this->purgeCommittedRowsOnMySql();

        parent::tearDown();
    }

    public function test_dry_run_writes_nothing(): void
    {
        $this->artisan('make:auth-module', [
            'name' => $this->name,
            '--dry-run' => true,
        ])->assertExitCode(0);

        $this->assertFileDoesNotExist(app_path("Models/{$this->name}.php"));
        $this->assertStringNotContainsString(
            "// AUTH-MODULE: {$this->guard}",
            File::get($this->authModulesConfigPath)
        );
    }

    public function test_generates_expected_files_and_registers_config(): void
    {
        $this->artisan('make:auth-module', [
            'name' => $this->name,
            '--login' => 'email,phone',
            '--with-tests' => true,
        ])->assertExitCode(0);

        $expectedFiles = [
            app_path("Models/{$this->name}.php"),
            database_path("factories/{$this->name}Factory.php"),
            app_path("Services/Functional/{$this->name}AuthService.php"),
            app_path("Http/Controllers/Auth/{$this->name}AuthController.php"),
            app_path("Http/Resources/Model/{$this->name}Resource.php"),
            app_path("Facades/Services/Auth/{$this->name}AuthFacade.php"),
            app_path("Policies/{$this->name}Policy.php"),
            base_path("routes/api/v1/{$this->routeFile}.php"),
            base_path("tests/Feature/{$this->name}AuthModuleTest.php"),
        ];

        foreach ($expectedFiles as $path) {
            $this->assertFileExists($path, "Expected generated file missing: {$path}");
        }

        $migrations = File::glob(database_path("migrations/*_create_{$this->table}_table.php"));
        $this->assertCount(1, $migrations);

        foreach ($expectedFiles as $path) {
            $this->assertSame(
                '',
                shell_exec('php -l '.escapeshellarg($path).' 2>&1 | grep -v "No syntax errors"') ?: '',
                "Generated file has a syntax error: {$path}"
            );
        }

        $config = File::get($this->authModulesConfigPath);
        $this->assertStringContainsString("// AUTH-MODULE: {$this->guard}", $config);
        $this->assertStringContainsString("'guard' => '{$this->guard}'", $config);
        $this->assertStringContainsString("'managed_by_generator' => true", $config);

        $serviceContent = File::get(app_path("Services/Functional/{$this->name}AuthService.php"));
        $this->assertStringContainsString("'prefix_phone'", $serviceContent);
    }

    public function test_generator_is_idempotent_on_rerun(): void
    {
        $this->artisan('make:auth-module', ['name' => $this->name])->assertExitCode(0);
        $this->artisan('make:auth-module', ['name' => $this->name])
            ->expectsOutputToContain('already exists')
            ->assertExitCode(0);

        $config = File::get($this->authModulesConfigPath);
        $this->assertSame(1, substr_count($config, "// AUTH-MODULE: {$this->guard}"));
    }

    public function test_registration_without_otp_is_rejected_and_writes_nothing(): void
    {
        $this->artisan('make:auth-module', [
            'name' => $this->name,
            '--registration' => true,
        ])->assertExitCode(1);

        $this->assertFileDoesNotExist(app_path("Models/{$this->name}.php"));
        $this->assertStringNotContainsString(
            "// AUTH-MODULE: {$this->guard}",
            File::get($this->authModulesConfigPath)
        );
    }

    public function test_social_identifier_is_declared_but_never_generated_in_service_code(): void
    {
        $this->artisan('make:auth-module', [
            'name' => $this->name,
            '--login' => 'email,social',
        ])->assertExitCode(0);

        $serviceContent = File::get(app_path("Services/Functional/{$this->name}AuthService.php"));
        $this->assertStringNotContainsString('social_id', $serviceContent);

        $config = File::get($this->authModulesConfigPath);
        $this->assertStringContainsString("'login_identifiers' => ['email', 'social']", $config);
    }

    public function test_routes_are_disabled_by_default(): void
    {
        $this->artisan('make:auth-module', ['name' => $this->name])->assertExitCode(0);

        $routesContent = File::get(base_path("routes/api/v1/{$this->routeFile}.php"));

        $this->assertStringNotContainsString("\nRoute::prefix('{$this->routeFile}')", $routesContent);
        $this->assertStringContainsString("// Route::prefix('{$this->routeFile}')", $routesContent);
    }

    public function test_enable_routes_flag_produces_a_live_uncommented_routes_file(): void
    {
        $this->artisan('make:auth-module', [
            'name' => $this->name,
            '--enable-routes' => true,
        ])->assertExitCode(0);

        $routesContent = File::get(base_path("routes/api/v1/{$this->routeFile}.php"));

        $this->assertStringContainsString("\nRoute::prefix('{$this->routeFile}')", $routesContent);
        $this->assertStringContainsString('guard.identity:'.$this->guard, $routesContent);
    }

    public function test_with_seeder_registers_permission_seeder_in_database_seeder_idempotently(): void
    {
        $this->artisan('make:auth-module', [
            'name' => $this->name,
            '--with-seeder' => true,
        ])->assertExitCode(0);

        $seederContent = File::get($this->databaseSeederPath);
        $this->assertSame(1, substr_count($seederContent, 'AuthModulesPermissionSeeder'));

        // Re-running --with-seeder (e.g. via a second, different module)
        // must not duplicate the registration.
        File::put($this->authModulesConfigPath, $this->authModulesConfigOriginal);
        foreach (File::glob(app_path("Models/{$this->name}.php")) as $p) {
            File::delete($p);
        }

        $this->artisan('make:auth-module', [
            'name' => $this->name,
            '--with-seeder' => true,
        ])->assertExitCode(0);

        $seederContent = File::get($this->databaseSeederPath);
        $this->assertSame(1, substr_count($seederContent, 'AuthModulesPermissionSeeder'));
    }

    /**
     * Phase 3B (2026-10-25). Proves --otp generates a REAL working
     * register -> verify -> login flow, not a 501 placeholder — the
     * central claim of this phase's generator upgrade.
     *
     * Deliberately does NOT use the RefreshDatabase trait: this class's
     * other tests never touch the database, and RefreshDatabase caches
     * "already migrated" as a process-wide static flag (set by whichever
     * test in the whole suite run happens to use it first) — a migration
     * file that is only created by THIS test, mid-suite, would never be
     * picked up by that caching. Instead, the one migration this test
     * actually needs is run explicitly, by path, against the same sqlite
     * `:memory:` test connection every other test already uses (per
     * phpunit.xml) — not a real database, and no different in kind from
     * what RefreshDatabase itself does under the hood.
     */
    public function test_otp_flag_generates_a_real_register_verify_login_flow(): void
    {
        Cache::flush();
        FakeOtpChannel::reset();

        $this->artisan('make:auth-module', [
            'name' => $this->name,
            '--otp' => true,
        ])->assertExitCode(0);

        // The generator edits config/auth_modules.php on disk, but this
        // test's app was already booted (and its config() repository
        // already loaded) before that write — force-reload just this
        // namespace from the now-updated file.
        config(['auth_modules' => include $this->authModulesConfigPath]);

        $migrations = File::glob(database_path("migrations/*_create_{$this->table}_table.php"));
        $this->assertCount(1, $migrations);

        // No --path restriction: this test's class has no RefreshDatabase,
        // so core tables the OTP engine needs (otps, etc.) may not exist
        // on this connection yet either. Plain `migrate` only applies
        // whatever is actually still pending — everything, if this test
        // happens to run first in the suite; just the one new file, if an
        // earlier RefreshDatabase test already migrated everything else
        // on this same shared sqlite `:memory:` connection.
        $this->artisan('migrate', ['--force' => true])->assertExitCode(0);

        Route::post("/__test/{$this->guard}/register", function (RegisterRequest $request) {
            try {
                return response()->json(app("App\\Services\\Functional\\{$this->name}AuthService")->register($request));
            } catch (HttpResponseException $e) {
                return $e->getResponse();
            }
        });
        Route::post("/__test/{$this->guard}/verify", function (RegisterVerifyRequest $request) {
            try {
                return response()->json(app("App\\Services\\Functional\\{$this->name}AuthService")->verifyOtp($request));
            } catch (HttpResponseException $e) {
                return $e->getResponse();
            }
        });
        Route::post("/__test/{$this->guard}/login", function (LoginRequest $request) {
            try {
                return response()->json(app("App\\Services\\Functional\\{$this->name}AuthService")->login($request));
            } catch (HttpResponseException $e) {
                return $e->getResponse();
            }
        });

        $register = $this->postJson("/__test/{$this->guard}/register", [
            'name' => 'Generated Flow User',
            'email' => 'generated-flow@example.com',
            'password' => 'secret123',
            'password_confirmation' => 'secret123',
            'otp_delivery_method' => 'fake',
        ]);
        $register->assertStatus(200, 'register(): '.$register->getContent());

        $modelClass = "App\\Models\\{$this->name}";
        $account = $modelClass::where('email', 'generated-flow@example.com')->first();
        $this->assertNotNull($account, 'register() did not create the account row.');

        $code = FakeOtpChannel::lastCodeFor($account, 'register');
        $this->assertNotNull($code, 'No OTP code was captured for the generated register() flow.');

        $verify = $this->postJson("/__test/{$this->guard}/verify", [
            'id' => $account->id,
            'otp' => $code,
            'purpose' => 'register',
        ]);
        $verify->assertStatus(200, 'verifyOtp(): '.$verify->getContent());
        $this->assertNotEmpty($verify->json('token'));

        $login = $this->postJson("/__test/{$this->guard}/login", [
            'email' => 'generated-flow@example.com',
            'password' => 'secret123',
        ]);
        $login->assertStatus(200, 'login(): '.$login->getContent());
        $this->assertNotEmpty($login->json('token'));

        // Phase 3C: 'reset_password' is in the default --otp-actions set
        // (register,resend_register,reset_password) — proves
        // sendResetOtp()/verifyResetOtp()/resetPassword(), all INHERITED
        // from BaseAuthService (not generated per-module code), genuinely
        // work for a module make:auth-module just created, not just for
        // the hand-written Admin/User.
        Route::post("/__test/{$this->guard}/password/send-otp", function (SendResetOtpRequest $request) {
            try {
                return response()->json(app("App\\Services\\Functional\\{$this->name}AuthService")->sendResetOtp($request));
            } catch (HttpResponseException $e) {
                return $e->getResponse();
            }
        });
        Route::post("/__test/{$this->guard}/password/verify-otp", function (VerifyResetOtpRequest $request) {
            try {
                return response()->json(app("App\\Services\\Functional\\{$this->name}AuthService")->verifyResetOtp($request));
            } catch (HttpResponseException $e) {
                return $e->getResponse();
            }
        });
        Route::post("/__test/{$this->guard}/password/reset", function (ResetPasswordRequest $request) {
            try {
                return response()->json(app("App\\Services\\Functional\\{$this->name}AuthService")->resetPassword($request));
            } catch (HttpResponseException $e) {
                return $e->getResponse();
            }
        });

        FakeOtpChannel::reset();

        $this->postJson("/__test/{$this->guard}/password/send-otp", [
            'actor' => 'user',
            'email' => 'generated-flow@example.com',
            'channel' => 'fake',
        ])->assertStatus(200);

        $resetCode = FakeOtpChannel::lastCodeFor($account, 'reset_password');
        $this->assertNotNull($resetCode, 'No OTP code was captured for the generated module\'s reset_password flow.');

        $verifyReset = $this->postJson("/__test/{$this->guard}/password/verify-otp", [
            'actor' => 'user',
            'email' => 'generated-flow@example.com',
            'otp' => $resetCode,
        ]);
        $verifyReset->assertStatus(200, 'verifyResetOtp(): '.$verifyReset->getContent());
        $resetToken = $verifyReset->json('reset_token');
        $this->assertNotEmpty($resetToken);

        $reset = $this->postJson("/__test/{$this->guard}/password/reset", [
            'actor' => 'user',
            'email' => 'generated-flow@example.com',
            'reset_token' => $resetToken,
            'password' => 'brand-new-secret',
            'password_confirmation' => 'brand-new-secret',
        ]);
        $reset->assertStatus(200, 'resetPassword(): '.$reset->getContent());
        $this->assertTrue(Hash::check('brand-new-secret', $account->fresh()->password));
    }
}
